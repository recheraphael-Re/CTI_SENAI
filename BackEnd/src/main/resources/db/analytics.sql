-- Aplicar manualmente no mesmo banco do backend. Não altera tabelas existentes em public.
CREATE SCHEMA IF NOT EXISTS cti_analytics;
-- ===== LOTES (cada envio de planilha é um lote; criado e gravado só pelo PYTHON) =====
CREATE TABLE IF NOT EXISTS cti_analytics.upload_lote (                          -- tabela dos lotes
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,         -- id do lote
  arquivo_nome     VARCHAR(255) NOT NULL,                                       -- nome do arquivo enviado
  enviado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,                -- data e hora do envio
  status           VARCHAR(20) NOT NULL,                                        -- PROCESSANDO, PROCESSADO ou ERRO (quem grava é o Python)
  total_linhas     INT NOT NULL DEFAULT 0,                                      -- total de linhas da planilha
  linhas_validas   INT NOT NULL DEFAULT 0,                                      -- quantas estavam válidas
  linhas_invalidas INT NOT NULL DEFAULT 0,                                      -- quantas tinham erro
  linhas_com_aviso INT NOT NULL DEFAULT 0,                                      -- quantas tinham só aviso
  mensagem         VARCHAR(500)                                                 -- mensagem mostrada na tela
);

-- ===== DADOS VÁLIDOS (gravados pelo Python depois da limpeza) =====
CREATE TABLE IF NOT EXISTS cti_analytics.consultor (                            -- consultores, sem repetir
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,                    -- id do consultor
  nome  VARCHAR(120) NOT NULL UNIQUE                                            -- nome único
);
CREATE TABLE IF NOT EXISTS cti_analytics.segmento (                             -- segmentos de mercado, sem repetir
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,                    -- id do segmento
  nome  VARCHAR(40) NOT NULL UNIQUE                                             -- nome único (Indústria, Comércio...)
);
CREATE TABLE IF NOT EXISTS cti_analytics.servico (                              -- serviços oferecidos, sem repetir
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,                    -- id do serviço
  nome  VARCHAR(120) NOT NULL UNIQUE                                            -- nome único (Internet Dedicada, Firewall...)
);
CREATE TABLE IF NOT EXISTS cti_analytics.cliente (                              -- clientes válidos
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,       -- id do cliente
  lote_id            BIGINT NOT NULL REFERENCES cti_analytics.upload_lote(id) ON DELETE CASCADE,
  codigo_cti         VARCHAR(60) NOT NULL,                                      -- código do cliente
  nome               VARCHAR(255) NOT NULL,                                     -- nome do cliente
  consultor_id       BIGINT NOT NULL REFERENCES cti_analytics.consultor(id),
  segmento_id        BIGINT NOT NULL REFERENCES cti_analytics.segmento(id),
  nivel              CHAR(1) NOT NULL,                                          -- nível A, B ou C
  faturamento_anual  NUMERIC(16,2) NOT NULL,                                    -- FATURAMENTO ANUAL com 2 casas (base da média e da mediana)
  cidade             VARCHAR(120),                                              -- cidade
  uf                 CHAR(2),                                                   -- UF
  UNIQUE (lote_id, codigo_cti)                                                  -- não repete o código dentro do lote
);
CREATE TABLE IF NOT EXISTS cti_analytics.contrato (                             -- contratos por cliente
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,        -- id do contrato
  cliente_id        BIGINT NOT NULL REFERENCES cti_analytics.cliente(id) ON DELETE CASCADE,
  servico_id        BIGINT NOT NULL REFERENCES cti_analytics.servico(id),
  data_contratacao  DATE NOT NULL,                                              -- data da contratação
  UNIQUE (cliente_id, servico_id)                                               -- o cliente não contrata o mesmo serviço duas vezes
);

-- ===== RESULTADO DAS CONTAS (o dashboard lê daqui) =====
CREATE TABLE IF NOT EXISTS cti_analytics.estatistica_lote (                     -- um resultado por lote
  lote_id    BIGINT PRIMARY KEY REFERENCES cti_analytics.upload_lote(id) ON DELETE CASCADE,
  gerado_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,                      -- quando o Python gerou
  resultado  TEXT NOT NULL                                                      -- JSON com média, mediana e dados dos gráficos
);

