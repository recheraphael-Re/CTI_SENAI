-- CTI SENAI em PostgreSQL. Estrutura correspondente às entidades JPA atuais.
-- Aplicar junto de analytics.sql no banco configurado para Java e Python.
-- CREATE IF NOT EXISTS permite reexecutar sem remover dados existentes.
CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    criado_em TIMESTAMPTZ(6),
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('USER', 'ADMIN')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE', 'ATIVO', 'BLOQUEADO'))
);
CREATE TABLE IF NOT EXISTS public.consultor (
    id_consultor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha VARCHAR(150) NOT NULL,
    telefone VARCHAR(30)
);
CREATE TABLE IF NOT EXISTS public.cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cti VARCHAR(50),
    faixa_faturamento VARCHAR(100),
    id_consultor BIGINT NOT NULL REFERENCES public.consultor(id_consultor),
    nome_empresa VARCHAR(180) NOT NULL,
    segmento VARCHAR(100) NOT NULL,
    faturamento_anual NUMERIC(15,2) NOT NULL,
    nivel VARCHAR(255) NOT NULL CHECK (nivel IN ('A', 'B', 'C')),
    status VARCHAR(255) NOT NULL CHECK (status IN ('ATIVO', 'INATIVO'))
);
CREATE TABLE IF NOT EXISTS public.servico (
    id_servico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    categoria VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS public.contrato (
    id_contrato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inicio DATE NOT NULL,
    status VARCHAR(30) NOT NULL,
    id_cliente BIGINT NOT NULL REFERENCES public.cliente(id_cliente),
    id_servico BIGINT NOT NULL REFERENCES public.servico(id_servico)
);
CREATE TABLE IF NOT EXISTS public.insight (
    id_insight BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(100) NOT NULL,
    descricao VARCHAR(2000) NOT NULL,
    gerado_em TIMESTAMP(6) NOT NULL,
    id_cliente BIGINT NOT NULL REFERENCES public.cliente(id_cliente),
    id_contrato BIGINT REFERENCES public.contrato(id_contrato)
);
CREATE TABLE IF NOT EXISTS public.telemetria (
    id_telemetria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento VARCHAR(150) NOT NULL,
    status VARCHAR(30) NOT NULL,
    timestamp TIMESTAMP(6) NOT NULL,
    resultado VARCHAR(2000),
    mensagem_erro VARCHAR(2000),
    id_servico BIGINT NOT NULL REFERENCES public.servico(id_servico),
    id_contrato BIGINT NOT NULL REFERENCES public.contrato(id_contrato)
);
