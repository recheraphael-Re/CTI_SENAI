-- No DBeaver, selecione o banco de destino e execute este arquivo inteiro.
-- Cria objetos no schema cti. Não cria banco, usuários ou credenciais.
-- IF NOT EXISTS permite repetir a criação, mas não atualiza tabelas antigas.
BEGIN;
CREATE SCHEMA IF NOT EXISTS cti;

CREATE TABLE IF NOT EXISTS cti.consultores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(50) UNIQUE,
    nome VARCHAR(200) NOT NULL CHECK (btrim(nome) <> ''),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cti.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cti VARCHAR(50) NOT NULL UNIQUE CHECK (btrim(codigo_cti) <> ''),
    empresa VARCHAR(250) NOT NULL CHECK (btrim(empresa) <> ''),
    consultor_id BIGINT NOT NULL REFERENCES cti.consultores(id),
    segmento VARCHAR(150) NOT NULL CHECK (btrim(segmento) <> ''),
    nivel CHAR(1) NOT NULL CHECK (nivel IN ('A', 'B', 'C')),
    faturamento NUMERIC(18,2) NOT NULL CHECK (faturamento >= 0),
    periodo_faturamento VARCHAR(20) NOT NULL
        CHECK (periodo_faturamento IN ('MENSAL', 'ANUAL', 'NAO_INFORMADO')),
    faturamento_original TEXT,
    faturamento_estimado BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cti.servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL UNIQUE CHECK (btrim(nome) <> ''),
    categoria VARCHAR(100),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cti.contratos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_contrato VARCHAR(80) UNIQUE,
    cliente_id BIGINT NOT NULL REFERENCES cti.clientes(id),
    servico_id BIGINT NOT NULL REFERENCES cti.servicos(id),
    valor_servico NUMERIC(18,2) CHECK (valor_servico >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'NAO_INFORMADO'
        CHECK (status IN ('ATIVO', 'PENDENTE', 'CANCELADO', 'NAO_INFORMADO')),
    data_inicio DATE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Permite verificar se o contrato de um insight pertence ao cliente informado.
    UNIQUE (id, cliente_id)
);

CREATE TABLE IF NOT EXISTS cti.importacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_arquivo TEXT NOT NULL CHECK (btrim(nome_arquivo) <> ''),
    nome_aba VARCHAR(100) NOT NULL DEFAULT 'dados_importacao',
    total_colunas INTEGER CHECK (total_colunas >= 0),
    periodo_faturamento VARCHAR(20) NOT NULL DEFAULT 'NAO_INFORMADO'
        CHECK (periodo_faturamento IN ('MENSAL', 'ANUAL', 'NAO_INFORMADO')),
    status VARCHAR(20) NOT NULL DEFAULT 'PROCESSANDO'
        CHECK (status IN ('PROCESSANDO', 'CONCLUIDA', 'FALHOU')),
    enviado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalizado_em TIMESTAMPTZ,
    CHECK (finalizado_em IS NULL OR finalizado_em >= enviado_em)
);

-- Área de importação: admite campos vazios, valores negativos e códigos repetidos.
-- Guardar cada linha aqui ANTES de promover dados válidos para as tabelas de domínio.
CREATE TABLE IF NOT EXISTS cti.registros_importados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT NOT NULL REFERENCES cti.importacoes(id),
    linha_excel INTEGER NOT NULL CHECK (linha_excel > 0),
    dados_originais JSONB NOT NULL CHECK (jsonb_typeof(dados_originais) = 'object'),
    dados_tratados JSONB CHECK (jsonb_typeof(dados_tratados) = 'object'),
    status_validacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_validacao IN ('PENDENTE', 'VALIDO', 'INVALIDO')),
    cliente_id BIGINT REFERENCES cti.clientes(id),
    contrato_id BIGINT REFERENCES cti.contratos(id),
    UNIQUE (importacao_id, linha_excel),
    FOREIGN KEY (contrato_id, cliente_id) REFERENCES cti.contratos(id, cliente_id),
    CHECK (contrato_id IS NULL OR cliente_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS cti.erros_validacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registro_id BIGINT NOT NULL REFERENCES cti.registros_importados(id),
    tipo VARCHAR(60) NOT NULL CHECK (btrim(tipo) <> ''),
    campo VARCHAR(100) NOT NULL CHECK (btrim(campo) <> ''),
    descricao TEXT NOT NULL CHECK (btrim(descricao) <> '')
);

CREATE TABLE IF NOT EXISTS cti.insights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT REFERENCES cti.importacoes(id),
    cliente_id BIGINT REFERENCES cti.clientes(id),
    contrato_id BIGINT REFERENCES cti.contratos(id),
    tipo VARCHAR(60) NOT NULL CHECK (btrim(tipo) <> ''),
    descricao TEXT NOT NULL CHECK (btrim(descricao) <> ''),
    indicadores JSONB NOT NULL DEFAULT '{}'::JSONB,
    gerado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (contrato_id, cliente_id) REFERENCES cti.contratos(id, cliente_id),
    CHECK (contrato_id IS NULL OR cliente_id IS NOT NULL),
    CHECK (importacao_id IS NOT NULL OR cliente_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS cti.telemetria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT REFERENCES cti.importacoes(id),
    evento VARCHAR(80) NOT NULL CHECK (btrim(evento) <> ''),
    status VARCHAR(20) NOT NULL CHECK (status IN ('INICIADO', 'SUCESSO', 'ERRO')),
    mensagem TEXT,
    duracao_ms BIGINT CHECK (duracao_ms >= 0),
    detalhes JSONB NOT NULL DEFAULT '{}'::JSONB,
    registrado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_clientes_consultor ON cti.clientes(consultor_id);
CREATE INDEX IF NOT EXISTS idx_contratos_cliente ON cti.contratos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_contratos_servico ON cti.contratos(servico_id);
CREATE INDEX IF NOT EXISTS idx_erros_registro ON cti.erros_validacao(registro_id);
CREATE INDEX IF NOT EXISTS idx_insights_importacao ON cti.insights(importacao_id);
CREATE INDEX IF NOT EXISTS idx_insights_cliente ON cti.insights(cliente_id);
CREATE INDEX IF NOT EXISTS idx_insights_contrato ON cti.insights(contrato_id);
CREATE INDEX IF NOT EXISTS idx_telemetria_importacao ON cti.telemetria(importacao_id);
CREATE INDEX IF NOT EXISTS idx_registros_cliente ON cti.registros_importados(cliente_id);
CREATE INDEX IF NOT EXISTS idx_registros_contrato ON cti.registros_importados(contrato_id);

COMMIT;

-- Resultado esperado: nove tabelas no schema cti.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'cti' AND table_type = 'BASE TABLE'
ORDER BY table_name;
